/* Text in the engine font (assets/font.txt), and a basic chat log. */
#include <string.h>
#include "world.h"

extern const uint8_t font_glyphs[95][FONT_H]; /* generated by tools/font2c.py */

int text_width(const char *s)
{
    return (int)strlen(s) * FONT_ADVANCE;
}

void text_draw(const char *s, int x, int y, void (*rect)(int x, int y, int w, int h, void *ctx), void *ctx)
{
    for (; *s; s++, x += FONT_ADVANCE) {
        int c = *s >= ' ' && *s <= '~' ? *s : '?';
        const uint8_t *rows = font_glyphs[c - ' '];
        for (int r = 0; r < FONT_H; r++) {
            /* Runs of lit pixels along the row: bit 4 is the leftmost. */
            for (int i = 0; i < FONT_W;) {
                if (!(rows[r] >> (FONT_W - 1 - i) & 1)) {
                    i++;
                    continue;
                }
                int start = i;
                while (i < FONT_W && rows[r] >> (FONT_W - 1 - i) & 1)
                    i++;
                rect(x + start, y + r, i - start, 1, ctx);
            }
        }
    }
}

void chat_say(chat_log *log, const char *who, const char *msg, int now)
{
    /* "who: msg", keeping only printable ASCII, the message cut to CHAT_MAX. */
    char line[CHAT_COLS * 3];
    int n = 0;
    for (const char *s = who; *s && n < CHAT_COLS; s++)
        if (*s >= ' ' && *s <= '~')
            line[n++] = *s;
    line[n++] = ':';
    line[n++] = ' ';
    int kept = 0;
    for (const char *s = msg; *s && kept < CHAT_MAX; s++)
        if (*s >= ' ' && *s <= '~')
            line[n++] = *s, kept++;

    /* Wrapped CHAT_COLS across, at the last space that fits (mid-word if that would leave the
     * line under half full); the oldest lines scroll off the top. */
    for (int at = 0, len; at < n; at += len) {
        if (log->count == CHAT_LINES) {
            memmove(log->lines[0], log->lines[1], sizeof log->lines[0] * (CHAT_LINES - 1));
            memmove(&log->said[0], &log->said[1], sizeof log->said[0] * (CHAT_LINES - 1));
            log->count--;
        }
        len = n - at < CHAT_COLS ? n - at : CHAT_COLS;
        int shown = len;
        if (at + len < n) {
            int space = len;
            while (space > CHAT_COLS / 2 && line[at + space] != ' ')
                space--;
            if (space > CHAT_COLS / 2) /* else a long word: break it rather than leave a short line */
                shown = space, len = space + 1; /* the space itself isn't shown */
        }
        memcpy(log->lines[log->count], line + at, (size_t)shown);
        log->lines[log->count][shown] = '\0';
        log->said[log->count++] = now;
    }
}
