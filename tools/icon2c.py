"""Embed a PNG as RGBA pixels, for a window icon.

    python3 tools/icon2c.py assets/icon/icon-64.png build/gen/icon.c app_icon

Writes `const int NAME_w, NAME_h;` and `const unsigned char NAME[w * h * 4]` (rows top to
bottom, r, g, b, a). Standard library only.
"""
import os
import sys

from texload import read_png

src, dst, name = sys.argv[1:4]
(w, h), pixel = read_png(src)
data = bytes(c for y in range(h) for x in range(w) for c in pixel(x, y))
with open(dst, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'/* Generated by tools/icon2c.py from {src.replace(os.sep, "/")}; do not edit. */\n')
    f.write(f'const int {name}_w = {w}, {name}_h = {h};\n')
    f.write(f'const unsigned char {name}[] = {{\n')
    for i in range(0, len(data), 16):
        f.write('    ' + ' '.join(f'0x{b:02x},' for b in data[i:i + 16]) + '\n')
    f.write('};\n')
