"""Build the engine font (assets/font.txt, ASCII art) into C.

    python3 tools/font2c.py assets/font.txt build/gen/font.c

Writes `const uint8_t font_glyphs[95][7]`: printable ASCII from the space, one byte per row,
bit 4 the leftmost of the 5 pixels. Standard library only.
"""
import os
import sys

src, dst = sys.argv[1], sys.argv[2]
glyphs, name, rows = {}, None, []


def finish():
    if name is None:
        return
    ch = ' ' if name == 'space' else name
    if len(ch) != 1 or not ' ' <= ch <= '~':
        sys.exit(f'{src}: bad glyph name "{name}"')
    if len(rows) != 7 or any(len(r) != 5 or set(r) - set('.#') for r in rows):
        sys.exit(f'{src}: glyph "{name}" should be 7 rows of 5 "." or "#"')
    if ch in glyphs:
        sys.exit(f'{src}: glyph "{name}" twice')
    glyphs[ch] = [sum(1 << (4 - i) for i, c in enumerate(r) if c == '#') for r in rows]


for line in open(src, encoding='utf-8'):
    line = line.rstrip('\n')
    if line.startswith('#') and not line.startswith('##') and ' ' in line[:2]:
        continue  # a comment ("# ...")
    if line.startswith('== '):
        finish()
        name, rows = line[3:], []
    elif line:
        rows.append(line)
finish()
missing = [chr(c) for c in range(32, 127) if chr(c) not in glyphs]
if missing:
    sys.exit(f'{src}: no glyphs for {"".join(missing)!r}')

with open(dst, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'/* Generated by tools/font2c.py from {src.replace(os.sep, "/")}; do not edit. */\n')
    f.write('#include <stdint.h>\n\n')
    f.write('const uint8_t font_glyphs[95][7] = {\n')
    for c in range(32, 127):
        f.write('    {' + ', '.join(f'0x{b:02x}' for b in glyphs[chr(c)]) + f'}}, /* {chr(c)!r} */\n')
    f.write('};\n')
