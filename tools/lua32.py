"""Write lua32.h: Lua's luaconf.h with LUA_32BITS switched on, followed by lua.h and lauxlib.h,
plus a lower limit on nested C calls.

    python3 tools/lua32.py third_party/lua/luaconf.h build/gen/lua32.h

luaconf.h hard-codes LUA_32BITS to 0 and the submodule stays unmodified, so the core includes
this instead of lua.h. It is included first, and luaconf.h's include guard then makes Lua's
own includes of luaconf.h do nothing.
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
conf, n = re.subn(r'^#define LUA_32BITS\s+0\b', '#define LUA_32BITS\t1', open(src).read(), flags=re.M)
if n != 1:
    sys.exit(f'lua32: no "#define LUA_32BITS 0" in {src}')
with open(dst, 'w', newline='\n') as f:
    f.write(f'/* Generated by tools/lua32.py from {src}; do not edit. */\n')
    # Nested C calls and parser levels (Lua's default is 200): each costs C stack, and the DS
    # has little, so deeply nested input must stop early.
    f.write('#define LUAI_MAXCCALLS 64\n')
    f.write(conf)
    f.write('\n#include "lua.h"\n#include "lauxlib.h"\n')
